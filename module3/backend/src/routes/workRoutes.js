import {Router} from 'express';
import upload from '../middleware/upload.js';
import auth,{allowRole} from '../middleware/auth.js';
import Work from '../models/Work.js';
import {listWorks,addMilestone,updateMilestone,deleteMilestone,submitMilestone,reviewMilestone,downloadDeliverable,cancelWork,completeWork,rateWork} from '../controllers/workController.js';
const r=Router();
r.use(auth);
r.get('/',listWorks);
r.post('/:id/milestones',allowRole('client'),addMilestone);
r.patch('/:id/milestones/:milestoneId',allowRole('client'),updateMilestone);
r.delete('/:id/milestones/:milestoneId',allowRole('client'),deleteMilestone);
r.post('/:id/milestones/:milestoneId/upload',allowRole('student'),async(req,res,next)=>{try{const w=await Work.findOne({_id:req.params.id,studentId:req.user._id,status:'active'});if(!w)return res.status(404).json({message:'Active work not found.'});const m=w.milestones.id(req.params.milestoneId);if(!m)return res.status(404).json({message:'Milestone not found.'});if(!['pending','revision'].includes(m.status))return res.status(409).json({message:'This milestone is not accepting uploads.'});req.workRecord=w;req.milestoneRecord=m;next();}catch(e){next(e)}},upload.single('deliverable'),async(req,res,next)=>{try{const w=req.workRecord;const m=req.milestoneRecord;if(!req.file)return res.status(400).json({message:'Choose a file to upload.'});m.deliverableFile=req.file.filename;m.deliverableUrl=`/api/works/${w._id}/milestones/${m._id}/download`;await w.save();res.status(201).json({work:w,deliverableUrl:m.deliverableUrl});}catch(e){next(e)}});
r.get('/:id/milestones/:milestoneId/download',downloadDeliverable);
r.patch('/:id/milestones/:milestoneId/submit',allowRole('student'),submitMilestone);
r.patch('/:id/milestones/:milestoneId/review',allowRole('client'),reviewMilestone);
r.patch('/:id/cancel',allowRole('client'),cancelWork);
r.patch('/:id/complete',allowRole('client'),completeWork);
r.patch('/:id/rating',allowRole('client'),rateWork);
export default r;
